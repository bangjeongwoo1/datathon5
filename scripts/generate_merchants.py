"""Generate browser data from the coordinate-enriched merchant CSV."""
from __future__ import annotations
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / 'data'
OUTPUT = ROOT / 'frontend' / 'src' / 'data' / 'merchants.generated.ts'
INDUSTRY_OVERRIDES = {883: '양식'}

def coordinate_source() -> Path:
    sources = [path for path in DATA_DIR.iterdir() if path.suffix == '.csv' and path.name.startswith('A_')]
    enriched = sorted((path for path in sources if '_보완' in path.stem), key=lambda path: (path.stem.count('_보완'), path.name))
    return enriched[0] if enriched else next(iter(sources))

def text(value: str | None) -> str:
    return (value or '').strip()

def coordinates(row: dict[str, str]) -> dict[str, float] | None:
    try:
        lat, lng = float(row['위도']), float(row['경도'])
        return {'lat': lat, 'lng': lng} if -90 <= lat <= 90 and -180 <= lng <= 180 else None
    except (KeyError, TypeError, ValueError):
        return None

def main() -> None:
    records: list[dict[str, object]] = []
    with coordinate_source().open(encoding='utf-8-sig', newline='') as source:
        for row in csv.DictReader(source):
            name, address, industry = text(row.get('가맹점명')), text(row.get('소재지도로명주소')), text(row.get('업종명'))
            if not name or not address or not industry:
                continue
            merchant_id = int(row['가맹점ID'])
            record: dict[str, object] = {'id': merchant_id, 'name': name, 'address': address, 'industry': INDUSTRY_OVERRIDES.get(merchant_id, industry), 'officialBusinessType': text(row.get('공식_업태명'))}
            if point := coordinates(row): record['coordinates'] = point
            records.append(record)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("// Generated by scripts/generate_merchants.py. Do not edit manually.\nimport type { SourceMerchant } from '../merchantData.ts'\n\nexport const sourceMerchants: SourceMerchant[] = " + json.dumps(records, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    print(f'Generated {len(records)} merchants ({sum("coordinates" in item for item in records)} with coordinates)')

if __name__ == '__main__': main()
